#!/usr/bin/env python3
"""Generates THIRD-PARTY-NOTICES.md: every Rust crate compiled into the release
targets, every npm package shipped in the frontend bundle, and the bundled native
components (llama.cpp, LLVM OpenMP, the Microsoft Visual C++ runtime).

    python3 scripts/notices.py            # writes THIRD-PARTY-NOTICES.md
    python3 scripts/notices.py --check    # fails if the file is out of date

Uses `cargo metadata` (no network) and node_modules; license texts come from each
package's own LICENSE / COPYING / NOTICE files.
"""

import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD-PARTY-NOTICES.md"
TARGETS = ["x86_64-pc-windows-msvc", "aarch64-apple-darwin"]
LICENSE_FILES = ("LICENSE", "LICENCE", "COPYING", "NOTICE", "UNLICENSE")


def license_texts(directory: pathlib.Path) -> list[tuple[str, str]]:
    out = []
    if not directory.is_dir():
        return out
    for f in sorted(directory.iterdir()):
        if f.is_file() and f.name.upper().startswith(LICENSE_FILES):
            try:
                out.append((f.name, f.read_text(encoding="utf-8", errors="replace").strip()))
            except OSError:
                pass
    return out


def grouped_texts(items: list[tuple[str, pathlib.Path]]) -> list[str]:
    """Each distinct license text once, followed by the packages that ship it."""
    by_text: dict[str, list[str]] = {}
    for label, directory in items:
        for _, text in license_texts(directory):
            # Normalise whitespace so trivially reflowed copies group together.
            key = " ".join(text.split())
            by_text.setdefault(key, [])
            if label not in by_text[key]:
                by_text[key].append(label)
            by_text.setdefault("__raw__" + key, [text])
    out = []
    keys = sorted((k for k in by_text if not k.startswith("__raw__")), key=lambda k: by_text[k][0].lower())
    for k in keys:
        users = by_text[k]
        out += [f"Used by: {', '.join(users)}", "", "```text", by_text["__raw__" + k][0], "```", ""]
    return out


def rust_packages() -> list[dict]:
    seen = {}
    for target in TARGETS:
        meta = json.loads(
            subprocess.run(
                ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", target],
                cwd=ROOT, check=True, capture_output=True, text=True,
            ).stdout
        )
        nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
        pkgs = {p["id"]: p for p in meta["packages"]}
        # Walk normal (non-dev, non-build) dependencies from the app.
        app = next(p["id"] for p in meta["packages"] if p["name"] == "app")
        stack, reach = [app], set()
        while stack:
            pid = stack.pop()
            if pid in reach:
                continue
            reach.add(pid)
            for dep in nodes[pid]["deps"]:
                if any(k["kind"] in (None, "normal") for k in dep["dep_kinds"]):
                    stack.append(dep["pkg"])
        for pid in reach:
            p = pkgs[pid]
            if p["source"] is None:
                continue  # our own workspace crates
            seen[(p["name"], p["version"])] = p
    return sorted(seen.values(), key=lambda p: (p["name"].lower(), p["version"]))


def npm_packages() -> list[dict]:
    lock = json.loads((ROOT / "package-lock.json").read_text())
    out = []
    for path, info in sorted(lock.get("packages", {}).items()):
        if not path.startswith("node_modules/") or info.get("dev") or info.get("devOptional"):
            continue
        name = path.split("node_modules/")[-1]
        out.append({"name": name, "version": info.get("version", ""), "license": info.get("license", "unknown"), "dir": ROOT / path})
    return out


def render() -> str:
    lines = [
        "# Third-party notices",
        "",
        "harnissUI includes the software listed below. Each entry gives the license under which it is used;",
        "full license texts follow each group. This file is generated by `scripts/notices.py`; do not edit it by hand.",
        "",
        "## Bundled native components",
        "",
    ]
    for title, f, note in [
        ("llama.cpp (llama-server, llama-fit-params) — MIT", "llama.cpp-LICENSE", "Pinned build b12110; see llama.lock.json."),
        ("LLVM OpenMP runtime (Windows, libomp.dll) — Apache-2.0 WITH LLVM-exception", "LLVM-OpenMP-LICENSE", ""),
    ]:
        lines += [f"### {title}", ""]
        if note:
            lines += [note, ""]
        text = (ROOT / "third_party" / "licenses" / f).read_text(encoding="utf-8").strip()
        lines += ["```text", text, "```", ""]
    lines += [
        "### Microsoft Visual C++ runtime (Windows: msvcp140.dll, vcruntime140.dll, vcruntime140_1.dll)",
        "",
        "Redistributed under the Microsoft Visual Studio redistributable code terms",
        "(https://learn.microsoft.com/visualstudio/releases/2022/redistribution).",
        "",
        "Optional GPU backends (CUDA, ROCm) are not part of the installer. They are downloaded only when you",
        "click Download in Settings, after their licenses are shown.",
        "",
        "## Rust crates",
        "",
    ]
    rust = rust_packages()
    lines += ["| Crate | Version | License |", "|---|---|---|"]
    for p in rust:
        lines.append(f"| {p['name']} | {p['version']} | {p.get('license') or 'see text'} |")
    lines += ["", "### License texts (Rust)", ""]
    lines += grouped_texts([(f"{p['name']} {p['version']}", pathlib.Path(p["manifest_path"]).parent) for p in rust])
    lines += ["## npm packages (frontend bundle)", "", "| Package | Version | License |", "|---|---|---|"]
    npm = npm_packages()
    for p in npm:
        lines.append(f"| {p['name']} | {p['version']} | {p['license']} |")
    lines += ["", "### License texts (npm)", ""]
    lines += grouped_texts([(f"{p['name']} {p['version']}", p["dir"]) for p in npm])
    return "\n".join(lines) + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("THIRD-PARTY-NOTICES.md is out of date; run python3 scripts/notices.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT} ({len(text) // 1024} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
