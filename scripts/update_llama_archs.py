#!/usr/bin/env python3
"""Regenerates catalog/llama-architectures.txt from the llama.cpp commit pinned in
llama.lock.json, so the model browser can warn before downloading a model whose
architecture the bundled llama-server cannot load (ARCHITECTURE.md 11).

Run after changing the pin:   python3 scripts/update_llama_archs.py
  --source DIR   read DIR/src/llama-arch.cpp from a local checkout of llama.cpp instead of
                 raw.githubusercontent.com. DIR must be a git checkout whose HEAD is the
                 pinned commit, so a wrong folder can never write a wrong list.
  --check        write nothing; exit 1 if the committed list differs from what the pinned
                 commit gives (and print the names added and removed).
"""
from __future__ import annotations

import argparse
import json
import pathlib
import re
import subprocess
import sys
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "catalog" / "llama-architectures.txt"


def parse_names(src: str) -> list[str]:
    """The `general.architecture` values of the LLM_ARCH_NAMES table in src/llama-arch.cpp."""
    start = src.index("LLM_ARCH_NAMES")
    block = src[start : src.index("};", start)]
    names = [n for n in re.findall(r'\{\s*LLM_ARCH_\w+,\s*"([^"]+)"\s*\}', block) if n != "(unknown)"]
    if len(names) < 50:
        raise SystemExit(f"only {len(names)} architectures found; the source layout may have changed")
    return names


def render(tag: str, commit: str, names: list[str]) -> str:
    return (
        f"# general.architecture values known to llama.cpp {tag} ({commit}).\n"
        "# Generated by scripts/update_llama_archs.py; do not edit by hand.\n"
        + "\n".join(names)
        + "\n"
    )


def read_source(commit: str, checkout: pathlib.Path | None) -> str:
    if checkout is None:
        url = f"https://raw.githubusercontent.com/ggml-org/llama.cpp/{commit}/src/llama-arch.cpp"
        return urllib.request.urlopen(url, timeout=60).read().decode()
    head = subprocess.run(
        ["git", "-C", str(checkout), "rev-parse", "HEAD"], capture_output=True, text=True, check=False
    )
    if head.returncode != 0 or head.stdout.strip() != commit:
        raise SystemExit(f"{checkout} is not a git checkout of the pinned commit {commit}")
    return (checkout / "src" / "llama-arch.cpp").read_text(encoding="utf-8")


def names_in(text: str) -> list[str]:
    return [l.strip() for l in text.splitlines() if l.strip() and not l.startswith("#")]


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--source", type=pathlib.Path, help="a local llama.cpp checkout at the pinned commit")
    ap.add_argument("--check", action="store_true", help="write nothing; fail if the committed list is stale")
    args = ap.parse_args(argv)

    lock = json.loads((ROOT / "llama.lock.json").read_text())
    commit = lock["llama_cpp"]["commit"]
    tag = lock["llama_cpp"]["tag"]
    names = parse_names(read_source(commit, args.source))
    text = render(tag, commit, names)

    old = OUT.read_text() if OUT.exists() else ""
    added = [n for n in names if n not in names_in(old)]
    removed = [n for n in names_in(old) if n not in names]
    if args.check:
        if old == text:
            print(f"{OUT.name} is current: {len(names)} architectures of llama.cpp {tag}")
            return 0
        print(f"{OUT.name} is stale for llama.cpp {tag} ({commit}); run scripts/update_llama_archs.py")
        print(f"  would add {len(added)}: {' '.join(added)}")
        print(f"  would remove {len(removed)}: {' '.join(removed)}")
        return 1
    OUT.write_text(text)
    print(f"{len(names)} architectures written to {OUT} (added {len(added)}, removed {len(removed)})")
    if added:
        print("  added:  " + " ".join(added))
    if removed:
        print("  removed: " + " ".join(removed))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
