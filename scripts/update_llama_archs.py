#!/usr/bin/env python3
"""Regenerates catalog/llama-architectures.txt from the llama.cpp commit pinned in
llama.lock.json, so the model browser can warn before downloading a model whose
architecture the bundled llama-server cannot load (ARCHITECTURE.md 11).

Run after changing the pin:  python3 scripts/update_llama_archs.py
"""
import json
import pathlib
import re
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
lock = json.loads((ROOT / "llama.lock.json").read_text())
commit = lock["llama_cpp"]["commit"]
tag = lock["llama_cpp"]["tag"]
url = f"https://raw.githubusercontent.com/ggml-org/llama.cpp/{commit}/src/llama-arch.cpp"
src = urllib.request.urlopen(url, timeout=60).read().decode()
start = src.index("LLM_ARCH_NAMES")
block = src[start : src.index("};", start)]
names = [n for n in re.findall(r'\{\s*LLM_ARCH_\w+,\s*"([^"]+)"\s*\}', block) if n != "(unknown)"]
if len(names) < 50:
    raise SystemExit(f"only {len(names)} architectures found; the source layout may have changed")
out = ROOT / "catalog" / "llama-architectures.txt"
out.write_text(
    f"# general.architecture values known to llama.cpp {tag} ({commit}).\n"
    "# Generated by scripts/update_llama_archs.py; do not edit by hand.\n"
    + "\n".join(names)
    + "\n"
)
print(f"{len(names)} architectures written to {out}")
