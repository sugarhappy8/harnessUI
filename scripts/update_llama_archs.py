#!/usr/bin/env python3
"""Regenerates catalog/llama-architectures.txt from the llama.cpp commit pinned in
llama.lock.json, so the model browser can warn before downloading a model whose
architecture the bundled llama-server cannot load (ARCHITECTURE.md 11).

Run after changing the pin:   python3 scripts/update_llama_archs.py
  --source DIR   read DIR/src/llama-arch.cpp from a local checkout of llama.cpp instead of
                 raw.githubusercontent.com. DIR must be a git checkout whose HEAD is the
                 pinned commit, so a wrong folder can never write a wrong list.
  --check        write nothing; exit 1 if the committed list differs from what the pinned
                 commit gives (and print the names added and removed).
  --pack rocm    do the same for catalog/llama-architectures-rocm.txt, from the llama.cpp
                 commit the ROCm download was built from (`upstream_llama_cpp_commit` of its
                 entry in llama.lock.json, written in full). That build is a second
                 llama.cpp: a name the main list has and this list lacks is a green Download
                 that fails at load on ROCm, and a test in crates/models fails for it.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import re
import subprocess
import sys
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "catalog" / "llama-architectures.txt"
OUT_ROCM = ROOT / "catalog" / "llama-architectures-rocm.txt"


def parse_names(src: str) -> list[str]:
    """The `general.architecture` values of the LLM_ARCH_NAMES table in src/llama-arch.cpp."""
    start = src.index("LLM_ARCH_NAMES")
    block = src[start : src.index("};", start)]
    names = [n for n in re.findall(r'\{\s*LLM_ARCH_\w+,\s*"([^"]+)"\s*\}', block) if n != "(unknown)"]
    if len(names) < 50:
        raise SystemExit(f"only {len(names)} architectures found; the source layout may have changed")
    return names


def render(what: str, commit: str, names: list[str]) -> str:
    return (
        f"# general.architecture values known to {what} ({commit}).\n"
        "# Generated by scripts/update_llama_archs.py; do not edit by hand.\n"
        + "\n".join(names)
        + "\n"
    )


def target(lock: dict, pack: str) -> tuple[str, str, pathlib.Path]:
    """What the list is made from (for its header), the full commit, and the file it goes to."""
    if pack == "main":
        return f"llama.cpp {lock['llama_cpp']['tag']}", lock["llama_cpp"]["commit"], OUT
    entry = next((p for p in lock.get("packs", []) if p.get("id") == pack), None)
    if entry is None:
        raise SystemExit(f"llama.lock.json has no pack {pack!r}")
    commit = entry.get("upstream_llama_cpp_commit")
    if not isinstance(commit, str) or not re.fullmatch(r"[0-9a-f]{40}", commit):
        raise SystemExit(
            f"the {pack} pack needs its upstream_llama_cpp_commit written as a full 40-character "
            f"commit in llama.lock.json (found {commit!r})"
        )
    return f"llama.cpp in the ROCm download {entry['build']}", commit, OUT_ROCM


def read_source(commit: str, checkout: pathlib.Path | None) -> str:
    if checkout is None:
        url = f"https://raw.githubusercontent.com/ggml-org/llama.cpp/{commit}/src/llama-arch.cpp"
        return urllib.request.urlopen(url, timeout=60).read().decode()
    head = subprocess.run(
        ["git", "-C", str(checkout), "rev-parse", "HEAD"], capture_output=True, text=True, check=False
    )
    if head.returncode != 0 or head.stdout.strip() != commit:
        raise SystemExit(f"{checkout} is not a git checkout of the pinned commit {commit}")
    return (checkout / "src" / "llama-arch.cpp").read_text(encoding="utf-8")


def names_in(text: str) -> list[str]:
    return [l.strip() for l in text.splitlines() if l.strip() and not l.startswith("#")]


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--source", type=pathlib.Path, help="a local llama.cpp checkout at the pinned commit")
    ap.add_argument("--check", action="store_true", help="write nothing; fail if the committed list is stale")
    ap.add_argument("--pack", choices=["main", "rocm"], default="main", help="which build's list (default: the main pin)")
    args = ap.parse_args(argv)

    lock = json.loads((ROOT / "llama.lock.json").read_text())
    what, commit, out = target(lock, args.pack)
    names = parse_names(read_source(commit, args.source))
    text = render(what, commit, names)

    old = out.read_text() if out.exists() else ""
    added = [n for n in names if n not in names_in(old)]
    removed = [n for n in names_in(old) if n not in names]
    # A second build knows fewer names than the list the model browser judges by: say so.
    lacks = (
        [n for n in names_in(OUT.read_text()) if n not in names]
        if args.pack != "main" and OUT.exists()
        else []
    )
    if args.check:
        if old == text:
            print(f"{out.name} is current: {len(names)} architectures of {what}")
        else:
            script = "scripts/update_llama_archs.py" + ("" if args.pack == "main" else f" --pack {args.pack}")
            print(f"{out.name} is stale for {what} ({commit}); run {script}")
            print(f"  would add {len(added)}: {' '.join(added)}")
            print(f"  would remove {len(removed)}: {' '.join(removed)}")
            return 1
    else:
        out.write_text(text)
        print(f"{len(names)} architectures written to {out} (added {len(added)}, removed {len(removed)})")
        if added:
            print("  added:  " + " ".join(added))
        if removed:
            print("  removed: " + " ".join(removed))
    if lacks:
        print(f"  note: it lacks {len(lacks)} names of the main list: {' '.join(lacks)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
